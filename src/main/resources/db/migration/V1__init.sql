-- V1: 初始结构。配额账户 + 用量记录。
-- 所有金额/配额均以 long 表示最小整数单位，避免浮点误差。
CREATE TABLE quota_account (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_name VARCHAR(128) NOT NULL,
    status       VARCHAR(16)  NOT NULL,
    total_quota  BIGINT       NOT NULL,
    remaining    BIGINT       NOT NULL,
    version      BIGINT       NOT NULL,
    created_at   BIGINT       NOT NULL,
    updated_at   BIGINT       NOT NULL,
    CONSTRAINT ck_quota_account_status  CHECK (status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT ck_quota_account_quota   CHECK (total_quota >= 0),
    CONSTRAINT ck_quota_account_remain  CHECK (remaining >= 0 AND remaining <= total_quota),
    CONSTRAINT uq_quota_account_name    UNIQUE (account_name)
);

CREATE TABLE usage_record (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT      NOT NULL,
    amount          BIGINT      NOT NULL,
    occurred_at     BIGINT      NOT NULL,
    business_ref    VARCHAR(128) NOT NULL,
    CONSTRAINT fk_usage_account FOREIGN KEY (account_id)
        REFERENCES quota_account (id),
    CONSTRAINT ck_usage_amount CHECK (amount > 0)
);

-- 游标翻页的稳定排序键：(account_id, occurred_at, id)
CREATE INDEX idx_usage_account_time_id
    ON usage_record (account_id, occurred_at, id);
